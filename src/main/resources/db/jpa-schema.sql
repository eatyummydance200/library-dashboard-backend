CREATE TABLE staff_jpa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(20) NOT NULL,
  phone VARCHAR(20) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (name)
);

CREATE TABLE teachers_jpa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(20) NOT NULL,
  extension VARCHAR(20) NOT NULL,
  phone VARCHAR(20) NOT NULL,
  position VARCHAR(40) NOT NULL,
  location VARCHAR(80) NOT NULL,
  UNIQUE (name)
);

CREATE TABLE users_jpa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(32) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(16) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  version BIGINT NOT NULL DEFAULT 1,
  staff_id BIGINT,
  UNIQUE (username),
  CHECK (role IN ('ADMIN','WORKER'))
);

CREATE TABLE shifts_jpa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id BIGINT NOT NULL,
  day DATE NOT NULL,
  start_minute INTEGER NOT NULL,
  end_minute INTEGER NOT NULL,
  role VARCHAR(16) NOT NULL,
  CHECK (start_minute >= 540 AND MOD(start_minute,30) = 0),
  CHECK (end_minute <= 1320 AND MOD(end_minute,30) = 0 AND end_minute > start_minute),
  CHECK (role IN ('DESK','GENERAL'))
);

CREATE TABLE original_schedule_weeks_jpa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  week DATE NOT NULL,
  updated_by BIGINT NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  UNIQUE (week)
);

CREATE TABLE original_shifts_jpa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  schedule_week_id BIGINT NOT NULL,
  staff_id BIGINT NOT NULL,
  day DATE NOT NULL,
  start_minute INTEGER NOT NULL,
  end_minute INTEGER NOT NULL,
  role VARCHAR(16) NOT NULL,
  CHECK (start_minute >= 540 AND MOD(start_minute,30) = 0),
  CHECK (end_minute <= 1320 AND MOD(end_minute,30) = 0 AND end_minute > start_minute),
  CHECK (role IN ('DESK','GENERAL'))
);

CREATE TABLE weekly_hour_overrides_jpa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  schedule_week_id BIGINT NOT NULL,
  staff_id BIGINT NOT NULL,
  total_minutes INTEGER NOT NULL,
  desk_minutes INTEGER NOT NULL,
  opens INTEGER NOT NULL,
  closes INTEGER NOT NULL,
  updated_by BIGINT NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  UNIQUE (schedule_week_id,staff_id),
  CHECK (total_minutes BETWEEN 0 AND 3900 AND MOD(total_minutes,30) = 0),
  CHECK (desk_minutes BETWEEN 0 AND 3900 AND MOD(desk_minutes,30) = 0 AND desk_minutes <= total_minutes),
  CHECK (opens BETWEEN 0 AND 5),
  CHECK (closes BETWEEN 0 AND 5)
);

CREATE TABLE issues_jpa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  day DATE NOT NULL,
  category VARCHAR(16) NOT NULL,
  title VARCHAR(80) NOT NULL,
  body VARCHAR(1500) NOT NULL,
  author_id BIGINT NOT NULL,
  done BOOLEAN NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE monthly_tags_jpa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id BIGINT NOT NULL,
  tag_year INTEGER NOT NULL,
  tag_month INTEGER NOT NULL,
  completed BOOLEAN NOT NULL,
  updated_by BIGINT NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  UNIQUE (staff_id,tag_year,tag_month),
  CHECK (tag_year BETWEEN 2000 AND 2100),
  CHECK (tag_month BETWEEN 1 AND 12)
);

CREATE TABLE archive_draws_jpa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  month DATE NOT NULL,
  created_by BIGINT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  UNIQUE (month)
);

CREATE TABLE archive_assignments_jpa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  draw_id BIGINT NOT NULL,
  group_number INTEGER NOT NULL,
  staff_id BIGINT NOT NULL,
  staff_name VARCHAR(20) NOT NULL,
  UNIQUE (draw_id,group_number),
  UNIQUE (draw_id,staff_id),
  CHECK (group_number BETWEEN 1 AND 7)
);

CREATE TABLE archive_tasks_jpa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id BIGINT NOT NULL,
  position INTEGER NOT NULL,
  newspaper VARCHAR(40) NOT NULL,
  completed BOOLEAN NOT NULL,
  completed_by BIGINT,
  completed_at TIMESTAMP WITH TIME ZONE,
  UNIQUE (assignment_id,position)
);

CREATE TABLE duty_contact_jpa (
  id BIGINT PRIMARY KEY,
  teacher VARCHAR(20) NOT NULL,
  extension VARCHAR(20) NOT NULL,
  day DATE,
  teacher_id BIGINT,
  phone VARCHAR(20) NOT NULL,
  CHECK (id = 1)
);

