CREATE TABLE staff (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE,
 phone TEXT NOT NULL DEFAULT '', active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1))
);
CREATE TABLE users (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT NOT NULL UNIQUE,
 password_hash TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('admin','worker')),
 active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)), version INTEGER NOT NULL DEFAULT 1,
 staff_id INTEGER REFERENCES staff(id)
);
CREATE TABLE teachers (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE,
 extension TEXT NOT NULL DEFAULT '', phone TEXT NOT NULL DEFAULT '',
 position TEXT NOT NULL DEFAULT '', location TEXT NOT NULL DEFAULT ''
);
CREATE TABLE shifts (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 staff_id INTEGER NOT NULL REFERENCES staff(id), day TEXT NOT NULL,
 start INTEGER NOT NULL CHECK(start>=540 AND start%30=0),
 "end" INTEGER NOT NULL CHECK("end"<=1320 AND "end"%30=0 AND "end">start),
 role TEXT NOT NULL CHECK(role IN ('desk','general'))
);
CREATE INDEX shifts_day ON shifts(day);
CREATE TABLE issues (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, day TEXT NOT NULL, category TEXT NOT NULL,
 title TEXT NOT NULL, body TEXT NOT NULL, author_id INTEGER NOT NULL REFERENCES users(id),
 done INTEGER NOT NULL DEFAULT 0 CHECK(done IN (0,1)),
 created_at TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE INDEX issues_day ON issues(day);
CREATE TABLE login_attempts (username TEXT NOT NULL, attempted_at BIGINT NOT NULL);
CREATE INDEX login_attempts_time ON login_attempts(username,attempted_at);
CREATE TABLE monthly_tags (
 staff_id INTEGER NOT NULL REFERENCES staff(id),
 year INTEGER NOT NULL CHECK(year BETWEEN 2000 AND 2100),
 month INTEGER NOT NULL CHECK(month BETWEEN 1 AND 12),
 completed INTEGER NOT NULL CHECK(completed IN (0,1)),
 updated_by INTEGER NOT NULL REFERENCES users(id), updated_at TEXT NOT NULL,
 PRIMARY KEY(staff_id,year,month)
);
CREATE TABLE archive_draws (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, month TEXT NOT NULL UNIQUE,
 created_by INTEGER NOT NULL REFERENCES users(id), created_at TEXT NOT NULL
);
CREATE TABLE archive_assignments (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 draw_id INTEGER NOT NULL REFERENCES archive_draws(id),
 group_number INTEGER NOT NULL CHECK(group_number BETWEEN 1 AND 7),
 staff_id INTEGER NOT NULL REFERENCES staff(id), staff_name TEXT NOT NULL,
 UNIQUE(draw_id,group_number), UNIQUE(draw_id,staff_id)
);
CREATE TABLE archive_tasks (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 assignment_id INTEGER NOT NULL REFERENCES archive_assignments(id),
 position INTEGER NOT NULL, newspaper TEXT NOT NULL,
 completed INTEGER NOT NULL DEFAULT 0 CHECK(completed IN (0,1)),
 completed_by INTEGER REFERENCES users(id), completed_at TEXT,
 UNIQUE(assignment_id,position)
);
CREATE TABLE duty_contact (
 id INTEGER PRIMARY KEY CHECK(id=1), teacher TEXT NOT NULL, extension TEXT NOT NULL,
 day TEXT NOT NULL DEFAULT '', teacher_id INTEGER REFERENCES teachers(id),
 phone TEXT NOT NULL DEFAULT ''
);

CREATE TABLE spring_session (
 primary_id CHAR(36) NOT NULL PRIMARY KEY, session_id CHAR(36) NOT NULL,
 creation_time BIGINT NOT NULL, last_access_time BIGINT NOT NULL,
 max_inactive_interval INTEGER NOT NULL, expiry_time BIGINT NOT NULL, principal_name VARCHAR(100)
);
CREATE UNIQUE INDEX spring_session_ix1 ON spring_session(session_id);
CREATE INDEX spring_session_ix2 ON spring_session(expiry_time);
CREATE INDEX spring_session_ix3 ON spring_session(principal_name);
CREATE TABLE spring_session_attributes (
 session_primary_id CHAR(36) NOT NULL REFERENCES spring_session(primary_id) ON DELETE CASCADE,
 attribute_name VARCHAR(200) NOT NULL, attribute_bytes BYTEA NOT NULL,
 PRIMARY KEY(session_primary_id,attribute_name)
);
