CREATE TABLE confirmed_shifts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id BIGINT NOT NULL REFERENCES staff(id),
  weekday INTEGER NOT NULL,
  start_minute INTEGER NOT NULL,
  end_minute INTEGER NOT NULL,
  role VARCHAR(16) NOT NULL,
  CHECK (weekday BETWEEN 1 AND 5),
  CHECK (start_minute >= 540 AND MOD(start_minute,30) = 0),
  CHECK (end_minute <= 1320 AND MOD(end_minute,30) = 0 AND end_minute > start_minute),
  CHECK (role IN ('DESK','GENERAL'))
);

CREATE TABLE staff_hour_overrides (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id BIGINT NOT NULL REFERENCES staff(id),
  total_minutes INTEGER NOT NULL,
  desk_minutes INTEGER NOT NULL,
  opens INTEGER NOT NULL,
  closes INTEGER NOT NULL,
  updated_by BIGINT NOT NULL REFERENCES users(id),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  UNIQUE (staff_id),
  CHECK (total_minutes BETWEEN 0 AND 3900 AND MOD(total_minutes,30) = 0),
  CHECK (desk_minutes BETWEEN 0 AND 3900 AND MOD(desk_minutes,30) = 0 AND desk_minutes <= total_minutes),
  CHECK (opens BETWEEN 0 AND 5 AND closes BETWEEN 0 AND 5)
);

INSERT INTO confirmed_shifts (staff_id,weekday,start_minute,end_minute,role)
SELECT s.staff_id,CAST(EXTRACT(ISODOW FROM s.day) AS INTEGER),s.start_minute,s.end_minute,s.role
FROM original_shifts s
WHERE s.schedule_week_id = (SELECT w.id FROM original_schedule_weeks w ORDER BY w.week DESC LIMIT 1)
ORDER BY s.day,s.start_minute,s.id;

INSERT INTO staff_hour_overrides (staff_id,total_minutes,desk_minutes,opens,closes,updated_by,updated_at)
SELECT o.staff_id,o.total_minutes,o.desk_minutes,o.opens,o.closes,o.updated_by,o.updated_at
FROM weekly_hour_overrides o
WHERE o.schedule_week_id = (SELECT w.id FROM original_schedule_weeks w ORDER BY w.week DESC LIMIT 1);

DROP TABLE weekly_hour_overrides;
DROP TABLE original_shifts;
DROP TABLE original_schedule_weeks;

CREATE INDEX confirmed_shifts_weekday ON confirmed_shifts(weekday);
