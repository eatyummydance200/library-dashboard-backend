CREATE TABLE original_schedule_weeks (
 week TEXT PRIMARY KEY,
 updated_by INTEGER NOT NULL REFERENCES users(id), updated_at TEXT NOT NULL
);
CREATE TABLE original_shifts (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 week TEXT NOT NULL REFERENCES original_schedule_weeks(week),
 staff_id INTEGER NOT NULL REFERENCES staff(id), day TEXT NOT NULL,
 start INTEGER NOT NULL CHECK(start>=540 AND start%30=0),
 "end" INTEGER NOT NULL CHECK("end"<=1320 AND "end"%30=0 AND "end">start),
 role TEXT NOT NULL CHECK(role IN ('desk','general'))
);
CREATE INDEX original_shifts_week ON original_shifts(week);
CREATE TABLE weekly_hour_overrides (
 week TEXT NOT NULL REFERENCES original_schedule_weeks(week),
 staff_id INTEGER NOT NULL REFERENCES staff(id),
 total_minutes INTEGER NOT NULL CHECK(total_minutes BETWEEN 0 AND 3900 AND total_minutes%30=0),
 desk_minutes INTEGER NOT NULL CHECK(desk_minutes BETWEEN 0 AND 3900 AND desk_minutes%30=0 AND desk_minutes<=total_minutes),
 opens INTEGER NOT NULL CHECK(opens BETWEEN 0 AND 5),
 closes INTEGER NOT NULL CHECK(closes BETWEEN 0 AND 5),
 updated_by INTEGER NOT NULL REFERENCES users(id), updated_at TEXT NOT NULL,
 PRIMARY KEY(week,staff_id)
);
