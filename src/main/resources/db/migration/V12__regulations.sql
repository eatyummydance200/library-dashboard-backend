CREATE TABLE regulations (
  id BIGINT PRIMARY KEY,
  content VARCHAR(200000) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_by VARCHAR(32) NOT NULL,
  CHECK (id = 1)
);

CREATE TABLE regulation_questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  question VARCHAR(500) NOT NULL,
  outcome VARCHAR(16) NOT NULL,
  answer VARCHAR(2000) NOT NULL,
  sources VARCHAR(4000) NOT NULL,
  model VARCHAR(64) NOT NULL,
  input_tokens INTEGER NOT NULL,
  output_tokens INTEGER NOT NULL,
  cache_read_tokens INTEGER NOT NULL,
  cache_write_tokens INTEGER NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  flagged_at TIMESTAMP WITH TIME ZONE,
  flag_note VARCHAR(500),
  resolved_at TIMESTAMP WITH TIME ZONE,
  CHECK (outcome IN ('answered','not_found','refused'))
);
CREATE INDEX regulation_questions_created_at ON regulation_questions (created_at);
